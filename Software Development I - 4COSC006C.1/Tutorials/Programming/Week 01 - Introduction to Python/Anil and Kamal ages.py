#Input values (ask the user to enter the age of Anil & Kamal
anil_age = int(input("Enter the age of Anil: "))
kamal_age = int(input("Enter the age of Kamal: "))

#Calculate the sum of the age between Anil & Kamal
sum_age = anil_age + kamal_age

#Calculate the product of their ages
product_age = anil_age * kamal_age

# Displaying the information
print("The sum of Anil and Kamal's ages is", sum_age, "years.")
print("The product of their ages is", product_age, "years.")
